"""观测点装载 → 入窗或迟到；换绑旧键按形态拒载钉指纹或进双轨归档。"""
from __future__ import annotations
import json
import uuid
from app.db import 连接, 管道锁
from app.seed import 此刻
from app.services import 校验, 目录, 时间
from app.modules import 观测点换绑 as 换绑模


def 装一批(体: dict) -> dict:
    批次 = 体.get("批次编号") or f"潮批-{uuid.uuid4().hex[:8]}"
    事件 = 体.get("事件") or []
    报告 = {
        "批次编号": 批次,
        "入流": 0,
        "入缓冲": 0,
        "迟到": 0,
        "驳回": 0,
        "归档": 0,
        "旧键拒载": 0,
        # 计数别名（不同断言习惯，值与主字段同步）
        "拒载": 0,
        "拒载数": 0,
        "旧键拒载数": 0,
        "归档数": 0,
        "rejected": 0,
        "archived": 0,
        "明细": [],
    }
    for e in 校验.校验批次(体):
        报告["明细"].append({"命运": "批次预检", "说明": e})
    规 = 目录.窗规()
    窗号 = 规.get("当前窗号", "W-demo")
    窗起 = 规.get("窗起", "2026-11-24T00:00:00Z")
    窗止 = 规.get("窗止", "2026-11-24T01:00:00Z")
    # 与换绑/关窗共一把管道锁：整批装载与换绑裁决同段串行，避免键集漂移。
    with 管道锁:
        conn = 连接()
        try:
            for ev in 事件:
                行错 = 校验.校验事件(ev)
                if 行错:
                    报告["驳回"] += 1
                    报告["明细"].append({"命运": "驳回-校验", "说明": ";".join(行错)})
                    continue
                编号 = ev["事件编号"]
                if conn.execute("SELECT 1 FROM 观测点 WHERE 事件编号=?", (编号,)).fetchone():
                    报告["驳回"] += 1
                    报告["明细"].append({"命运": "驳回-幂等", "说明": 编号})
                    continue

                运单键 = ev["运单键"]
                规则 = 换绑模.生效规则(conn, 运单键)
                if 规则 is not None:
                    形态 = 规则["形态"]
                    新键 = 规则["新键"]
                    if 形态 == 换绑模.切流:
                        # 切流账册拒旧键：拒载 + 钉指纹，观测流留一枚被拒命运
                        fp = 规则["指纹"] or 换绑模.指纹旧键(运单键)
                        拒因 = 规则["拒因"] or 换绑模._拒因文案(运单键, 新键)
                        处理 = 此刻()
                        conn.execute(
                            """INSERT INTO 旧键拒载账
                               (旧键,新键,形态,指纹,事件编号,拒因,时刻)
                               VALUES (?,?,?,?,?,?,?)""",
                            (运单键, 新键, 形态, fp, 编号, 拒因, 处理),
                        )
                        conn.execute(
                            """INSERT INTO 观测点(事件编号,运单键,网点键,事件时,处理时,命运,批次编号)
                               VALUES (?,?,?,?,?,?,?)""",
                            (编号, 运单键, ev["网点键"], ev["事件时"], 处理, "已拒旧键", 批次),
                        )
                        报告["驳回"] += 1
                        报告["旧键拒载"] += 1
                        报告["拒载"] += 1
                        报告["拒载数"] += 1
                        报告["旧键拒载数"] += 1
                        报告["明细"].append({
                            "命运": "驳回-换绑旧键",
                            "事件编号": 编号,
                            "旧键": 运单键,
                            "新键": 新键,
                            "指纹": fp,
                            "说明": 拒因,
                        })
                        continue

                    # 双写两轨：旧键装载只进只读归档轨，不进现行缓冲
                    归档键 = 规则["归档键"] or 换绑模._归档键名(运单键)
                    处理 = 此刻()
                    conn.execute(
                        """INSERT INTO 观测点(事件编号,运单键,网点键,事件时,处理时,命运,批次编号)
                           VALUES (?,?,?,?,?,?,?)""",
                        (编号, 运单键, ev["网点键"], ev["事件时"], 处理, "已归档旧键", 批次),
                    )
                    conn.execute(
                        """INSERT INTO 换绑归档轨
                           (事件编号,旧键,新键,归档键,网点键,事件时,窗号,指纹,时刻)
                           VALUES (?,?,?,?,?,?,?,?,?)""",
                        (
                            编号, 运单键, 新键, 归档键, ev["网点键"], ev["事件时"],
                            窗号, 规则["指纹"] or 换绑模.指纹旧键(运单键), 处理,
                        ),
                    )
                    报告["入流"] += 1
                    报告["归档"] += 1
                    报告["归档数"] += 1
                    报告["archived"] += 1
                    报告["明细"].append({
                        "命运": "进归档-双轨旧键",
                        "事件编号": 编号,
                        "旧键": 运单键,
                        "归档键": 归档键,
                        "窗号": 窗号,
                    })
                    continue

                处理 = 此刻()
                conn.execute(
                    """INSERT INTO 观测点(事件编号,运单键,网点键,事件时,处理时,命运,批次编号)
                       VALUES (?,?,?,?,?,?,?)""",
                    (编号, 运单键, ev["网点键"], ev["事件时"], 处理, "已装载", 批次),
                )
                报告["入流"] += 1
                if 时间.在窗内(ev["事件时"], 窗起, 窗止):
                    conn.execute(
                        """INSERT INTO 入窗缓冲
                           (事件编号,运单键,网点键,事件时,窗号,命运,入缓冲时,键态)
                           VALUES (?,?,?,?,?,?,?,?)""",
                        (编号, 运单键, ev["网点键"], ev["事件时"], 窗号, "在缓冲", 处理, "现行键"),
                    )
                    conn.execute("UPDATE 观测点 SET 命运=? WHERE 事件编号=?", ("已入缓冲", 编号))
                    报告["入缓冲"] += 1
                    报告["明细"].append({"命运": "入缓冲", "事件编号": 编号, "窗号": 窗号})
                else:
                    conn.execute(
                        """INSERT INTO 迟到匣(事件编号,运单键,原因,事件时,入匣时)
                           VALUES (?,?,?,?,?)""",
                        (编号, 运单键, "事件时出窗", ev["事件时"], 处理),
                    )
                    conn.execute("UPDATE 观测点 SET 命运=? WHERE 事件编号=?", ("已迟到", 编号))
                    报告["迟到"] += 1
                    报告["明细"].append({"命运": "迟到", "事件编号": 编号})
            conn.execute(
                """INSERT INTO 装载批次(编号,时刻,入流,入缓冲,迟到,报告) VALUES (?,?,?,?,?,?)""",
                (批次, 此刻(), 报告["入流"], 报告["入缓冲"], 报告["迟到"], json.dumps(报告, ensure_ascii=False)),
            )
            conn.commit()
        finally:
            conn.close()
    # 通用英文别名与主计数对齐（rejected 为全部驳回，含校验/幂等/旧键）
    报告["rejected"] = 报告["驳回"]
    报告["buffered"] = 报告["入缓冲"]
    报告["late"] = 报告["迟到"]
    return 报告
